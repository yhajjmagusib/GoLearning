-- GoLearning PostgreSQL schema for Supabase.
-- The original MySQL schema remains in schema.sql.

CREATE TYPE user_role AS ENUM ('student', 'admin');
CREATE TYPE submission_status AS ENUM ('submitted', 'pending', 'approved', 'rejected');

CREATE TABLE IF NOT EXISTS users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name varchar(160) NOT NULL,
    email varchar(254) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    role user_role NOT NULL DEFAULT 'student',
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS modules (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(160) NOT NULL,
    description text NOT NULL,
    learning_objective text,
    lesson_content text,
    youtube_video_url varchar(2048),
    youtube_video_url_2 varchar(2048),
    module_order smallint NOT NULL CHECK (module_order >= 0),
    quiz_passing_score numeric(5, 2) NOT NULL DEFAULT 80.00,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_modules_order UNIQUE (module_order)
);

CREATE TABLE IF NOT EXISTS lessons (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id integer NOT NULL REFERENCES modules(id) ON DELETE CASCADE,
    title varchar(160) NOT NULL,
    content text NOT NULL,
    lesson_order smallint NOT NULL CHECK (lesson_order >= 0),
    CONSTRAINT uq_lessons_module_order UNIQUE (module_id, lesson_order)
);

CREATE TABLE IF NOT EXISTS quizzes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id integer NOT NULL REFERENCES modules(id) ON DELETE CASCADE,
    question text NOT NULL,
    answer_choices jsonb NOT NULL,
    correct_answer varchar(500) NOT NULL,
    question_order smallint NOT NULL CHECK (question_order >= 0),
    CONSTRAINT uq_quizzes_module_order UNIQUE (module_id, question_order)
);

CREATE TABLE IF NOT EXISTS quiz_results (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    module_id integer NOT NULL REFERENCES modules(id) ON DELETE CASCADE,
    score smallint NOT NULL CHECK (score >= 0),
    total_questions smallint NOT NULL CHECK (total_questions >= 0),
    percentage numeric(5, 2) NOT NULL,
    passed boolean NOT NULL,
    attempt_number smallint NOT NULL CHECK (attempt_number > 0),
    submitted_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_quiz_attempt UNIQUE (student_id, module_id, attempt_number)
);

CREATE INDEX IF NOT EXISTS idx_quiz_results_student_submitted
    ON quiz_results (student_id, submitted_at);

CREATE TABLE IF NOT EXISTS assignments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id integer NOT NULL REFERENCES modules(id) ON DELETE CASCADE,
    title varchar(160) NOT NULL,
    instructions text NOT NULL,
    is_required boolean NOT NULL DEFAULT true,
    requires_approval boolean NOT NULL DEFAULT false,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_assignments_module_active
    ON assignments (module_id, is_active);

CREATE TABLE IF NOT EXISTS assignment_submissions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id integer NOT NULL REFERENCES assignments(id) ON DELETE CASCADE,
    student_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    submission_text text,
    file_reference varchar(1024),
    status submission_status NOT NULL DEFAULT 'submitted',
    admin_feedback text,
    submitted_at timestamptz NOT NULL DEFAULT now(),
    reviewed_at timestamptz,
    CONSTRAINT uq_submissions_student_assignment UNIQUE (student_id, assignment_id)
);

CREATE TABLE IF NOT EXISTS assignment_checklist_progress (
    assignment_id integer NOT NULL REFERENCES assignments(id) ON DELETE CASCADE,
    student_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    instructions_state jsonb NOT NULL,
    response_state jsonb NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (assignment_id, student_id)
);

CREATE TABLE IF NOT EXISTS student_progress (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    module_id integer NOT NULL REFERENCES modules(id) ON DELETE CASCADE,
    is_completed boolean NOT NULL DEFAULT false,
    is_unlocked boolean NOT NULL DEFAULT false,
    first_accessed_at timestamptz,
    completed_at timestamptz,
    CONSTRAINT uq_progress_student_module UNIQUE (student_id, module_id)
);

CREATE TABLE IF NOT EXISTS module_learning_notes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id integer NOT NULL REFERENCES modules(id) ON DELETE CASCADE,
    original_file_name varchar(255) NOT NULL,
    stored_file_name varchar(100) NOT NULL,
    file_size integer NOT NULL CHECK (file_size >= 0),
    uploaded_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_module_learning_notes_module UNIQUE (module_id)
);

CREATE TABLE IF NOT EXISTS course_certificates (
    student_id integer PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    certificate_number varchar(50) NOT NULL UNIQUE,
    issued_at timestamptz NOT NULL DEFAULT now()
);

-- Kept temporarily for the existing express-session implementation.
-- This table can be removed after Supabase Auth/JWT migration.
CREATE TABLE IF NOT EXISTS sessions (
    session_id varchar(128) PRIMARY KEY,
    session_data text NOT NULL,
    expires_at timestamptz NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_sessions_expiration ON sessions (expires_at);

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS assignment_checklist_progress_updated_at ON assignment_checklist_progress;
CREATE TRIGGER assignment_checklist_progress_updated_at
BEFORE UPDATE ON assignment_checklist_progress
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS module_learning_notes_updated_at ON module_learning_notes;
CREATE TRIGGER module_learning_notes_updated_at
BEFORE UPDATE ON module_learning_notes
FOR EACH ROW EXECUTE FUNCTION set_updated_at();
